create table if not exists public.disha_workspace_state (
  merchant_id uuid primary key references public.disha_merchants(id) on delete cascade,
  payload jsonb not null default '{"onHand":5,"billRecorded":69,"billExpected":96,"billNumber":1048,"salesTotal":14296,"billCount":62,"festivalMultiplier":1,"extraBills":[]}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.disha_proposals (
  id uuid primary key default gen_random_uuid(),
  merchant_id uuid references public.disha_merchants(id) on delete cascade,
  type text not null,
  status text not null default 'PROPOSED' check (status in ('PROPOSED', 'APPROVED', 'REJECTED', 'EXECUTED')),
  facts jsonb not null default '{}'::jsonb,
  reason text not null,
  narration text,
  fallback_used boolean not null default false,
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  outcome text,
  result jsonb
);

create index if not exists disha_proposals_merchant_status_idx
  on public.disha_proposals(merchant_id, status, created_at desc);

create table if not exists public.disha_audit_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  actor text not null,
  tool text not null,
  facts jsonb not null default '{}'::jsonb,
  narration text,
  validation_result text,
  decision text not null,
  outcome text,
  fallback_used boolean not null default false,
  merchant_id uuid references public.disha_merchants(id) on delete cascade
);

create index if not exists disha_audit_log_merchant_created_idx
  on public.disha_audit_log(merchant_id, created_at desc);

create table if not exists public.disha_outbox (
  id uuid primary key default gen_random_uuid(),
  proposal_id uuid not null references public.disha_proposals(id) on delete cascade,
  customer_id text not null,
  language text not null default 'en' check (language in ('en', 'te')),
  message_text text not null,
  sent_at timestamptz not null default now(),
  simulated boolean not null default true,
  merchant_id uuid references public.disha_merchants(id) on delete cascade
);

create table if not exists public.disha_purchase_drafts (
  id uuid primary key default gen_random_uuid(),
  proposal_id uuid not null references public.disha_proposals(id) on delete cascade,
  sku_id text not null,
  quantity integer not null check (quantity > 0),
  supplier_name text not null,
  created_at timestamptz not null default now(),
  status text not null default 'DRAFT' check (status in ('DRAFT', 'ORDERED', 'CANCELLED')),
  merchant_id uuid references public.disha_merchants(id) on delete cascade
);

