create extension if not exists pgcrypto;

create table if not exists public.disha_merchants (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) between 1 and 120),
  locale text not null default 'en-IN',
  timezone text not null default 'Asia/Kolkata',
  currency text not null default 'INR',
  status text not null default 'active' check (status in ('active', 'suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.disha_merchant_members (
  merchant_id uuid not null references public.disha_merchants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'staff' check (role in ('owner', 'manager', 'staff')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (merchant_id, user_id)
);

create index if not exists disha_merchant_members_user_idx
  on public.disha_merchant_members(user_id, created_at);

create table if not exists public.disha_demo_state (
  id text primary key,
  payload jsonb not null,
  audit_cursor bigint not null default 0,
  updated_at timestamptz not null default now(),
  merchant_id uuid references public.disha_merchants(id) on delete cascade
);

