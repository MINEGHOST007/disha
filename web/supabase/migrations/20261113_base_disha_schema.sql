drop policy if exists disha_membership_self_read on public.disha_merchant_members;
create policy disha_membership_self_read
  on public.disha_merchant_members for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists disha_proposals_member_read on public.disha_proposals;
create policy disha_proposals_member_read
  on public.disha_proposals for select to authenticated
  using (exists (
    select 1 from public.disha_merchant_members m
    where m.merchant_id = disha_proposals.merchant_id
      and m.user_id = (select auth.uid())
  ));

drop policy if exists disha_audit_member_read on public.disha_audit_log;
create policy disha_audit_member_read
  on public.disha_audit_log for select to authenticated
  using (exists (
    select 1 from public.disha_merchant_members m
    where m.merchant_id = disha_audit_log.merchant_id
      and m.user_id = (select auth.uid())
  ));

drop policy if exists disha_audit_member_insert on public.disha_audit_log;
create policy disha_audit_member_insert
  on public.disha_audit_log for insert to authenticated
  with check (exists (
    select 1 from public.disha_merchant_members m
    where m.merchant_id = disha_audit_log.merchant_id
      and m.user_id = (select auth.uid())
  ));

revoke all on public.disha_merchant_members, public.disha_proposals, public.disha_audit_log,
  public.disha_outbox, public.disha_purchase_drafts from anon;
revoke all on public.disha_merchants, public.disha_demo_state from authenticated;
grant select on public.disha_merchant_members, public.disha_proposals, public.disha_audit_log to authenticated;
grant insert on public.disha_proposals, public.disha_audit_log to authenticated;
